def raise_state(cancelled, date_from, date_to, today, row_states, grace_days=RAISE_GRACE_DAYS):
    """Статус тимчасової зміни: Скасовано → Майбутня → Задачу поставлено → До доплати → Діє (у межах дат). Після «До» без рядків «до доплати»:
    є місяці без годин (0 €) — «Нічого доплачувати», поки не мине grace_days днів після «До» (табелі вносять із запізненням — зміна щоночі
    перераховується, і внесені пізніше години дадуть доплату); потім — «Без годин» (виплаченого немає; видно у звірці) або «Виплачено».
    «Виплачено» — лише коли всі рядки з грошима відмічено «Виплачено» руками."""
    if cancelled:
        return 'cancel'
    if today < date_from:
        return 'future'
    if 'task' in row_states:
        return 'task'
    if 'due' in row_states:
        return 'due'
    if today <= date_to:
        return 'current'
    if 'skip' in row_states or 'paid' not in row_states:
        if today <= add_days(date_to, int(grace_days or 0)):
            return 'nothing'
        return 'paid' if 'paid' in row_states else 'nohours'
    return 'paid'


