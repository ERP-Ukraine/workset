def rule_pick(rules, line_id, cust_id, day):
    """Загальна ставка на day: найточніша діюча — рівня замовника (лінія + замовник), інакше рівня лінії (замовник порожній); з кількох —
    найпізніша «Ставка з» ≤ day. rules — [{'id', 'line_id', 'customer_id', 'date_from'}] активних правил → id або 0."""
    best = {True: None, False: None}
    if not line_id:
        return 0
    for r in rules:
        if r['line_id'] != line_id or not r['date_from'] or r['date_from'] > day:
            continue
        cust_level = bool(r.get('customer_id'))
        if cust_level and r['customer_id'] != cust_id:
            continue
        key = (r['date_from'], r['id'])
        if best[cust_level] is None or key > best[cust_level][0]:
            best[cust_level] = (key, r['id'])
    hit = best[True] or best[False]
    return hit[1] if hit else 0


RULE_PROTECTED = ('anchor', 'share_line_found', 'share_we_found', 'min_share', 'price_mode', 'fixed_month', 'car_rent')


def rule_guard(level, have, want):
    """Що з правил частки змінює не власник (група «правила ліній»): правило рівня лінії — цілком (будь-яка правка → ['level']);
    у тарифу замовника — захищені поля RULE_PROTECTED, значення яких ≠ наявному (have; для нового — якір лінії, «За годину», нулі).
    want — передані значення → список полів-порушень (порожній — можна)."""
    if level == 'line':
        return ['level'] if want else []
    bad = []
    for f in RULE_PROTECTED:
        if f not in want:
            continue
        if f in ('anchor', 'price_mode'):
            if (want[f] or False) != (have.get(f) or (False if f == 'anchor' else 'hour')):
                bad.append(f)
        elif not same_money(want[f], have.get(f)):
            bad.append(f)
    return bad


def found_share(found_by, share_line_found, share_we_found):
    """Частка за правилом за «Хто знайшов»: «Ми» — «Знайшли ми»; «Лінія» і не вказано — «Знайшла лінія» (не вказано — ще й у «Перевірити»)."""
    if found_by == 'us':
        return float(share_we_found or 0.0)
    return float(share_line_found or 0.0)


def rule_numbers(rule, wage, found_by, prev_price=0.0):
    """Ц, тип ціни й фікс за правилом (без «Своєї»). rule — {'anchor', 'price_mode', 'share_line_found', 'share_we_found', 'price', 'fixed_month'}
    або None (правила немає → None). Надбавка: Ц = Р + частка за «Хто знайшов». Тариф: Ц = ціна правила; ціни немає — ціна попередньої ставки
    пари (якір: росте Р — ціна та сама), а для першої ставки — стартова Р + частка. Фікс за місяць: Ц = Р (години передаються як є)."""
    if not rule:
        return None
    wage = float(wage or 0.0)
    mode = rule.get('price_mode') or 'hour'
    if mode == 'fixed_month':
        return {'price': round(wage, 2), 'price_mode': mode, 'fixed_month': round(float(rule.get('fixed_month') or 0.0), 2)}
    share = found_share(found_by, rule.get('share_line_found'), rule.get('share_we_found'))
    if rule.get('anchor') == 'tariff':
        if rule.get('price'):
            price = float(rule['price'])
        elif prev_price:
            price = float(prev_price)
        else:
            price = wage + share
    else:
        price = wage + share
    return {'price': round(price, 2), 'price_mode': 'hour', 'fixed_month': 0.0}


def same_numbers(have, want):
    """Числа ставки ({'price', 'price_mode', 'fixed_month'}) = правилу: тип, ціна, а в «Фікс за місяць» — і сума фіксу."""
    if (have.get('price_mode') or 'hour') != (want.get('price_mode') or 'hour') or not same_money(have.get('price'), want.get('price')):
        return False
    return want.get('price_mode') != 'fixed_month' or same_money(have.get('fixed_month'), want.get('fixed_month'))


def own_decision(edited, have, by_rule, was_own):
    """«Своя»: правила немає — ні (порівнювати нема з чим). Числа (Ц, тип, фікс) у цьому записі не правили — як було.
    Правили — «Своя», якщо вони ≠ правилу; збіглися з правилом — «Своя» знімається."""
    if not by_rule:
        return False
    if not edited:
        return bool(was_own)
    return not same_numbers(have, by_rule)


def hours_or_norm(month_hours, default_hours):
    """Години місяця для ділення: свої за минулий місяць, а немає — норма (→ (години, за нормою?))."""
    if (month_hours or 0) > 0:
        return float(month_hours), False
    return float(default_hours or MONTH_HOURS_DEFAULT), True


def shares(price_mode, wage, price, fixed_month, month_hours, default_hours, agent_client, agent_people, payer, bonus, fund=0.0, car_rent=0.0):
    """W і Ч за годину (до ZUS і податків на зарплату). «За годину»: W = Ц − Р − А_з − (А_л, якщо агенту людей платить WorkSET) − фонд
    працівників − оренда авто; «Фікс за місяць»: W = фікс ÷ години місяця (Ц = Р; як і посередник,
    фонд і оренда тут не віднімаються). Ч = W − Б."""
    if price_mode == 'fixed_month':
        hours, _norm = hours_or_norm(month_hours, default_hours)
        w = float(fixed_month or 0.0) / hours if hours else 0.0
    else:
        w = float(price or 0.0) - float(wage or 0.0) - float(agent_client or 0.0) - (float(agent_people or 0.0) if payer == 'workset' else 0.0) \
            - float(fund or 0.0) - float(car_rent or 0.0)
    w = round(w, 2)
    return {'our_share': w, 'net_share': round(w - float(bonus or 0.0), 2)}


def line_share(client_price, price):
    """П = К − Ц; К невідома — 0 (поле грошей не буває порожнім: «немає» — 0)."""
    if not client_price:
        return 0.0
    return round(float(client_price) - float(price or 0.0), 2)


