def up_and_back(versions, window):
    """Страж «вгору і назад»: versions — погодинні версії однієї картки [{'id', 'date', 'wage', 'temporary'}] (будь-який порядок).
    Версія A підняла ставку відносно попередньої, а версія B не пізніше за window днів після A повернула її до попередньої або нижче;
    жодна з двох не позначена «Тимчасово» → [{'a', 'b', 'base', 'up', 'back', 'a_date', 'b_date'}]."""
    rows = sorted(versions, key=lambda v: (v['date'], v['id']))
    out = []
    for i in range(1, len(rows)):
        a = rows[i]
        base = float(rows[i - 1]['wage'] or 0.0)
        if float(a['wage'] or 0.0) <= base + 0.005:
            continue
        for b in rows[i + 1:]:
            if (to_date(b['date']) - to_date(a['date'])).days > int(window or 0):
                break
            if float(b['wage'] or 0.0) <= base + 0.005:
                if not a.get('temporary') and not b.get('temporary'):
                    out.append({'a': a['id'], 'b': b['id'], 'base': base, 'up': float(a['wage']), 'back': float(b['wage']),
                                'a_date': a['date'], 'b_date': b['date']})
                break
    return out


