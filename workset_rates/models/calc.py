def contract_fallback(versions, gone_id):
    """Ставка з договору перестала бути базою версії gone_id, а на ту саму дату є інші версії договору людини [{'id', 'ok'}] (ok — діюча,
    не «Тимчасово», картка в периметрі, погодинна й ≤ поріг): ставка повертається до найновішої з них (більший id), а не в архів.
    → id версії або 0."""
    ids = [int(v['id']) for v in versions if v.get('ok') and int(v['id']) != int(gone_id or 0)]
    return max(ids) if ids else 0


