def own_stale(is_own, rate_rule_id, now_rule_id, now_rule_from, today, days=OWN_STALE_DAYS):
    """«Своя», а загальна ставка пари змінилась: на сьогодні діє інше правило, ніж те, на якому стоїть ставка, і воно діє довше за days днів
    (перші дні — ще не шум: людина встигне вирішити). Без зміни загальної «Своя» у «Звірку» не потрапляє."""
    if not is_own or not now_rule_id or now_rule_id == rate_rule_id or not now_rule_from:
        return False
    return add_days(now_rule_from, int(days)) < today


def raise_alert(state, date_to, today, soon=RAISE_SOON_DAYS):
    """Тимчасова зміна у «Звірку»: 'ending' — діє й закінчується за ≤ soon днів; 'due' — «До доплати» (у задачу ще не поставлено);
    'nohours' — «Без годин» (строк очікування табелів минув); інакше ''."""
    if state == 'current' and date_to and today <= date_to <= add_days(today, int(soon)):
        return 'ending'
    if state == 'due':
        return 'due'
    if state == 'nohours':
        return 'nohours'
    return ''


def panel_values(values, order_counts=None, keep_zero=False):
    """Значення лівої панелі без порожніх: прибрати ті, де лічильник 0 (keep_zero — залишити всі, напр. «Робота»), і впорядкувати за
    order_counts {id: число тих, хто працює} — більше вище; при рівності — за лічильником, далі — порядок, що дав Odoo."""
    rows = [v for v in values if keep_zero or v.get('__count', 1)]
    if order_counts is None:
        return rows
    counts = {str(k): n for k, n in order_counts.items()}  # ключі — id числом (Odoo) або рядком (JSON тестів)
    pos = {}
    for i, v in enumerate(rows):
        pos[v['id']] = i
    return sorted(rows, key=lambda v: (-(counts.get(str(v['id']), 0)), -(v.get('__count') or 0), pos[v['id']]))


def summary(rows):
    """Плитки підсумків над списком: rows — [{'work', 'wage', 'price', 'share'} + М2 'net' (чиста; немає — як частка), 'low' (W або Ч
    нижче мінімуму), 'raise' (є тимчасова зміна сьогодні), 'contract' (діюча ставка ≠ договору)] ставок поточного пошуку.
    Працюють — «Працює» + «Новий»; середні — по тих, хто працює; середні частка й чиста — без ставок з часткою ≤ 0 (їх число — «Без частки»),
    щоб їх можна було порівняти між собою; «Нижче мінімуму», «Тимчасових» і «Договір ≠ база» — серед тих, хто працює."""
    n = 0
    wage = 0.0
    price = 0.0
    share = 0.0
    net = 0.0
    ns = 0
    zero = 0
    low = 0
    raises = 0
    contract = 0
    for r in rows:
        if r['work'] not in ('work', 'work_new'):
            continue
        n += 1
        wage += r['wage'] or 0.0
        price += r['price'] or 0.0
        if r.get('low'):
            low += 1
        if r.get('raise'):
            raises += 1
        if r.get('contract'):
            contract += 1
        if (r['share'] or 0.0) > 0:
            share += r['share']
            net += r['net'] if r.get('net') is not None else r['share']
            ns += 1
        else:
            zero += 1
    return {'total': len(rows), 'working': n, 'avg_wage': round(wage / n, 2) if n else 0.0, 'avg_price': round(price / n, 2) if n else 0.0,
            'avg_share': round(share / ns, 2) if ns else 0.0, 'zero_share': zero, 'avg_net': round(net / ns, 2) if ns else 0.0,
            'below_min': low, 'raises': raises, 'contract_diff': contract}


