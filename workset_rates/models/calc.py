def office_bonus(rules, cust_id, line_id, person_id, day, month_hours, default_hours):
    """Б «Бонус офісу», €/год на day: Σ правил «€ за годину», що підходять замовнику й лінії, + Σ («€ за працівника на місяць» і
    «€ за своїх людей на місяць», де людина серед «Люди») ÷ години людини в цього замовника за минулий місяць (немає — норма).
    Порожні «Замовники» / «Лінії» — усі. «Лише оплачені» Б у плані не зменшує (умова виплати — для «Прибутковості»).
    rules — [{'id', 'kind', 'amount', 'customer_ids', 'line_ids', 'person_ids', 'date_from', 'date_to'}] → {'value', 'norm', 'ids'}."""
    hour = 0.0
    month = 0.0
    used = []
    for r in rules or []:
        if not in_dates(day, r.get('date_from'), r.get('date_to')):
            continue
        if r.get('customer_ids') and cust_id not in r['customer_ids']:
            continue
        if r.get('line_ids') and line_id not in r['line_ids']:
            continue
        if r['kind'] == 'own_worker_month' and person_id not in (r.get('person_ids') or []):
            continue
        if r['kind'] == 'hour':
            hour += float(r.get('amount') or 0.0)
        else:
            month += float(r.get('amount') or 0.0)
        used.append(r['id'])
    norm = False
    if month:
        hours, norm = hours_or_norm(month_hours, default_hours)
        hour += month / hours if hours else 0.0
    return {'value': round(hour, 2), 'norm': norm, 'ids': used}


def prev_month(day):
    """Минулий повний місяць відносно day → («перше число», «останнє число»)."""
    first = day[0:8] + '01'
    last = add_days(first, -1)
    return last[0:8] + '01', last


def month_bounds(day):
    first = day[0:8] + '01'
    nxt = add_days(first, 32)[0:8] + '01'
    return first, add_days(nxt, -1)


def sum_hours(rows, date_from, date_to):
    """rows — [[«РРРР-ММ-ДД», години]] табелів пари → години в межах «з – по» включно."""
    return round(sum(float(h or 0.0) for d, h in rows if date_from <= d <= date_to), 2)


def raise_months(kind, date_from, date_to, amount, rows, today):
    """Рядки «По місяцях» тимчасової зміни на today: лише місяці, що вже почались. «+€ за годину» — години пари в межах місяця × сума;
    рядок «до доплати» (due), коли його кінець (кінець місяця або «До») минув. «Разова сума» — один рядок у місяці «З», до доплати
    наступного дня після «До». → [{'month', 'date_from', 'date_to', 'hours', 'total', 'due'}]"""
    out = []
    if not date_from or not date_to or today < date_from:
        return out
    if kind == 'lump':
        return [{'month': date_from[0:8] + '01', 'date_from': date_from, 'date_to': date_to, 'hours': 0.0,
                 'total': round(float(amount or 0.0), 2), 'due': today > date_to}]
    first = date_from[0:8] + '01'
    while first <= date_to and first <= today:
        m_first, m_last = month_bounds(first)
        start = max(date_from, m_first)
        end = min(date_to, m_last)
        hours = sum_hours(rows, start, end)
        out.append({'month': m_first, 'date_from': start, 'date_to': end, 'hours': hours, 'total': round(hours * float(amount or 0.0), 2),
                    'due': today > end})
        first = add_days(m_last, 1)
    return out


