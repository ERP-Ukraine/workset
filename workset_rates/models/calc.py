    out = []
    for d in days:
        rows = [{'work': 'work', 'wage': r.get('wage'), 'price': r.get('price'), 'share': r.get('share'), 'net': r.get('net')}
                for r in rates if in_force(r.get('date_from'), r.get('date_to'), d)]
