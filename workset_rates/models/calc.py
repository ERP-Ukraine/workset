def short_date(day):
    """«РРРР-ММ-ДД» → «ДД.ММ» (серий підпис «до 30.11»)."""
    s = iso(day)
    return '%s.%s' % (s[8:10], s[5:7]) if s else ''


def raise_texts(wage, raises, today, lang):
    """Тимчасові зміни пари на today: raises — [{'kind', 'amount', 'date_from', 'date_to', 'cancel'}]; діють «+€ за годину», не скасовані,
    з «З» ≤ today ≤ «До». → {'now': на руки зараз, 'note': «зараз 17 до 30.11» (під «На руки» форми), 'badge': «+2 до 30.11» (бейдж дошки)};
    надбавки сьогодні немає — тексти порожні. «До» — найближче з тих, що діють."""
    live = [r for r in raises or [] if (r.get('kind') or 'hour') == 'hour' and not r.get('cancel') and r.get('date_from') and r.get('date_to')
            and r['date_from'] <= today <= r['date_to']]
    add = round(sum(float(r.get('amount') or 0.0) for r in live), 2)
    now = round(float(wage or 0.0) + add, 2)
    if not live or same_money(add, 0):
        return {'now': now, 'note': '', 'badge': ''}
    until = short_date(min(r['date_to'] for r in live))
    amount = ('+' if add > 0 else '') + money(add)
    return {'now': now, 'note': t('raise_note', lang) % (money(now), until), 'badge': t('raise_badge', lang) % (amount, until)}


