def housing_pick(rules, line_id, cust_id, day):
    """Правило житла на day: правило замовника (лінія + замовник) перекриває правило лінії (замовник порожній); «З» ≤ day ≤ «До» (порожнє —
    без кінця). rules — [{'id', 'line_id', 'customer_id' (комерційний, 0 — уся лінія), 'date_from', 'date_to'}] активних → id або 0."""
    best = {True: None, False: None}
    if not line_id:
        return 0
    for r in rules:
        if r['line_id'] != line_id or not r.get('date_from') or not in_dates(day, r['date_from'], r.get('date_to') or ''):
            continue
        cust_level = bool(r.get('customer_id'))
        if cust_level and r['customer_id'] != cust_id:
            continue
        key = (r['date_from'], r['id'])
        if best[cust_level] is None or key > best[cust_level][0]:
            best[cust_level] = (key, r['id'])
    hit = best[True] or best[False]
    return hit[1] if hit else 0


def housing_clash(rules, rule):
    """Одне правило житла на пару «лінія × замовник» на дату: rule — {'id', 'line_id', 'customer_id', 'date_from', 'date_to'}; rules — активні
    правила. → id правила тієї самої пари, чиї дати перетинаються (порожнє «До» — без кінця), або 0."""
    for r in rules:
        if r['id'] == rule['id'] or r['line_id'] != rule['line_id'] or (r.get('customer_id') or 0) != (rule.get('customer_id') or 0):
            continue
        if overlaps(rule['date_from'], rule.get('date_to') or FAR, r['date_from'], r.get('date_to') or FAR):
            return r['id']
    return 0


def housing_missing(pairs, rules, today):
    """Звірка «Лінія з надбавкою без правила житла» — покриття по парах (ревю М2c-1, № 6): pairs — [{'line_id', 'customer_id' (комерційний),
    'anchor' (якір лінії), 'rates' (діючих ставок пари)}]; лише якір «надбавка» з діючими ставками; пара, для якої на today немає правила
    ні замовника, ні лінії (housing_pick), → [(line_id, customer_id)] у порядку pairs. Правило іншого замовника пару не закриває; тарифні мовчать."""
    out = []
    for p in pairs:
        if p.get('anchor') != 'markup' or not p.get('rates'):
            continue
        if not housing_pick(rules, p['line_id'], p.get('customer_id') or 0, today):
            out.append((p['line_id'], p.get('customer_id') or 0))
    return out


