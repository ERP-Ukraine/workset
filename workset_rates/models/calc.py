def contract_action(rates, day, wage):
    """Що зробити зі ставками пари для версії договору з датою day і ставкою wage. rates — активні ставки пари [{'id', 'date_from', 'wage'}].
    → {'kind', 'rate'}: 'skip' — ставки на day немає (версія раніше за першу ставку пари: ставку «до початку роботи» не створюємо);
    'link' — ставка на day уже з цим «На руки» (лише позначити версію); 'update' — ставка з тією самою «Ставка з» (змінити її «На руки»,
    без дубля); 'create' — нова ставка з day, решта — копія ставки rate."""
    prev = None
    for r in sorted(rates, key=lambda x: (x['date_from'], x['id'])):
        if r['date_from'] <= day:
            prev = r
    if not prev:
        return {'kind': 'skip', 'rate': 0}
    if same_money(prev['wage'], wage):
        return {'kind': 'link', 'rate': prev['id']}
    if prev['date_from'] == day:
        return {'kind': 'update', 'rate': prev['id']}
    return {'kind': 'create', 'rate': prev['id']}


