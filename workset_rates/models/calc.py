def plural(n, one, few, many):
    """Форми числа (однакові правила в української й російської): 1 розбіжність, 2 розбіжності, 5 розбіжностей."""
    k = abs(int(n)) % 100
    if 11 <= k <= 14:
        return many
    k = k % 10
    if k == 1:
        return one
    if 2 <= k <= 4:
        return few
    return many


